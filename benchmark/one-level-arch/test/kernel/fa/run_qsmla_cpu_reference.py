#!/usr/bin/env python3
"""Build and run the unified QSMLA CPU golden generator by case name.

Purpose
=======
This is the case-driven front end.  It reads shape/window/scale metadata from
``qsmla_cases.py``, builds ``src/qsmla_cpu_reference.cpp`` once, and invokes
that executable to create deterministic FP16 inputs and an FP32 SWA golden.
Production CSA/HCA/sparse inputs are passed directly to the C++ executable;
they are not regenerated by this Stage-0 convenience command.

Common usage
============
List registered cases::

    python3 run_qsmla_cpu_reference.py --list

Generate one reference-feasible case::

    python3 run_qsmla_cpu_reference.py --case baseline_swa \
        --output-root /tmp/qsmla-reference

Generate every reference-feasible Stage-0 case::

    python3 run_qsmla_cpu_reference.py --all-reference \
        --output-root /tmp/qsmla-reference
"""

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

from qsmla_cases import QSMLA_STAGE0_CASES, QsmlaCase, validate_case


HERE = Path(__file__).resolve().parent
REFERENCE_SOURCE = HERE / "src" / "qsmla_cpu_reference.cpp"


def print_cases() -> None:
    print("NAME                              B    S1    S2   N1  N2    D    K   K1  MODE             Q/KV LAYOUT       LOGICAL/STORAGE -> STAGE0  ENABLE")
    for case in QSMLA_STAGE0_CASES:
        print(
            f"{case.name:32} {case.b:2} {case.s1:5} {case.s2:5} "
            f"{case.n1:4} {case.n2:3} {case.d:4} {case.k:4} "
            f"{('-' if case.k1 is None else str(case.k1)):>4}  {case.mode:16} "
            f"{case.q_layout}/{case.kv_layout:15} "
            f"{case.logical_dtype}/{case.source_storage_dtype} -> "
            f"{case.stage0_compute_dtype:5} {case.enable_stage}"
        )


def reference_args(case: QsmlaCase, output_root: Path):
    return [
        "--mode", "SWA", "--generate-deterministic",
        "--output-dir", str((output_root / case.name).resolve()),
        "--b", str(case.b), "--s1", str(case.s1),
        "--n1", str(case.n1), "--n2", str(case.n2),
        "--d", str(case.d), "--ori-s2", str(case.s2),
        "--win-left", str(case.win_left),
        "--win-right", str(case.win_right),
        "--softmax-scale", f"{case.softmax_scale:.9g}",
    ]


def run_references(cases, output_root: Path) -> None:
    for case in cases:
        error = validate_case(case)
        if error is not None:
            raise ValueError(f"invalid QSMLA case {case.name}: {error}")
        if not case.reference_feasible:
            raise ValueError(
                f"case {case.name} is a compile-shape target, not a CPU golden target")

    output_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="qsmla-cpu-reference-build-") as build_dir:
        binary = Path(build_dir) / "qsmla_cpu_reference"
        command = [
            "g++", "-std=c++20", "-O3", "-fopenmp", str(REFERENCE_SOURCE),
            "-o", str(binary),
        ]
        print("compile:", " ".join(command))
        subprocess.run(command, check=True)
        for case in cases:
            run_command = [str(binary), *reference_args(case, output_root)]
            print("reference:", " ".join(run_command))
            subprocess.run(run_command, check=True)


def parse_args():
    parser = argparse.ArgumentParser(
        description="List QSMLA cases and generate deterministic FP16 inputs plus CPU golden outputs")
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--list", action="store_true", help="list registered Stage-0 cases")
    action.add_argument("--case", metavar="NAME", help="generate one reference-feasible CPU golden")
    action.add_argument("--all-reference", action="store_true", help="generate every reference-feasible CPU golden")
    parser.add_argument("--output-root", type=Path, default=Path("qsmla_cpu_reference_output"))
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.list:
        print_cases()
        return 0
    by_name = {case.name: case for case in QSMLA_STAGE0_CASES}
    if args.case:
        case = by_name.get(args.case)
        if case is None:
            print(f"unknown QSMLA case: {args.case}", file=sys.stderr)
            return 2
        selected = (case,)
    else:
        selected = tuple(case for case in QSMLA_STAGE0_CASES if case.reference_feasible)
    try:
        run_references(selected, args.output_root)
    except (ValueError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
