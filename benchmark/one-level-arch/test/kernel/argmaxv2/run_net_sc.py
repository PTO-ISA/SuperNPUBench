#!/usr/bin/env python3
"""ArgMaxV2 single-core-scaled shape validation (acc gfrun + timing gfsim).

Cases from the single-core shape list argmax_net_single_core (8 shapes scaled
from the 121-chip 64-core comparison to single-core per-core workload).
Methodology mirrors run_net.py in this directory:
  accuracy: make res_check=on -> input.bin/golden (np.argmax, bit-exact,
            bf16 via top-16-bits fp32) -> gfrun -s softcore.multiThreadNum=4
            -> exact integer compare (atol=rtol=0);
  timing:   make SUFFIX=_t (res_check off, _start.s broadcasts main to 4PE)
            -> skill run_gfsim_matrix.sh (--conf fourpe --pto-v02 true,
            real L2, random SoC seed 2); DEADLOCK cases get the established
            single-variable diagnostic rerun (core.deadlock_cycles=1e6).

Usage: python3 run_net.py [--phase gen|acc|perf] [--run-jobs N]
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ARCH = HERE.parent.parent.parent                # .../one-level-arch
REPO = ARCH.parents[1]
OUTPUT = ARCH / "output/kernel/argmaxv2"
COMPARE = ARCH / "compare"
VALIDATION = REPO / ".validation/argmaxv2_net_sc"


def _req_env(name: str, hint: str) -> Path:
    """仓库约定（compile.all）：外部工具路径经环境变量注入，禁止硬编码。"""
    v = os.environ.get(name)
    if not v:
        sys.exit(f"error: 环境变量 {name} 未设置（{hint}）")
    return Path(v)

MODEL_DIR = _req_env("SUPERSCALAR_MODEL_DIR", "SuperScalarModel 仓库根目录（含 bin/gfsim、bin/gfrun）")
COMPILER_DIR = _req_env("COMPILER_DIR", "Linx 编译器 bin 目录（linx_blockisa_llvm_musl/bin）")
GFRUN = MODEL_DIR / "bin/gfrun"
SKILL_SCRIPT = _req_env("GFSIM_MATRIX_SCRIPT", "gfsim 矩阵执行脚本 run_gfsim_matrix.sh 路径（supernpu-gfsim-validation 技能）")

AXIS = 1  # all network cases reduce the last dim
GFRUN_TIMEOUT = 900
GFSIM_TIMEOUT = 3600  # net_2 ~5M cycles: ~45 min at ~2k cycles/s wall
DIAG_DEADLOCK_CYCLES = 1_000_000

# (cid, dims, dtype, idtype) — verbatim from argmax_net.xlsx
CASES = [
    ("argmax_net_sc_1", (1, 391), "bf16", "i64"),
    ("argmax_net_sc_2", (16, 25000), "bf16", "i64"),
    ("argmax_net_sc_3", (1, 77), "i32", "i64"),
    ("argmax_net_sc_4", (24, 2368), "fp32", "i64"),
    ("argmax_net_sc_5", (5, 2420), "fp32", "i64"),
    ("argmax_net_sc_6", (6, 2020), "fp32", "i32"),
    ("argmax_net_sc_7", (2, 391), "bf16", "i64"),
    ("argmax_net_sc_8", (8, 35000), "bf16", "i64"),
]

CTYPE = {"fp32": "float", "fp16": "__half", "bf16": "__bf16", "i32": "int32_t"}
NPDTYPE = {"fp32": np.float32, "fp16": np.float16, "bf16": None, "i32": np.int32}

CPP_TEMPLATE = """// Generated by run_net.py — ArgMaxV2 network case {cid}: {desc}
#include "benchmark.h"
#include "fileop.h"
#include "multi_thread_res_check.h"
#include "basic_op/argmaxv2/argmaxv2.hpp"

namespace {{
constexpr int kRank = {rank};
{dim_defs}
alignas(4096) {ctype} input[{total}];
alignas(4096) {idtype} output[{out_total}];
{size_asserts}
#ifdef RES_CHECK
MultiThreadResCheckSync res_check_sync{{}};
#endif
}}  // namespace

int main() {{
    const std::uint32_t tid = get_thread_idx();
#ifdef RES_CHECK
    if (tid == 0) {{
        readBinaryFile(CHK_DIR "/input.bin", reinterpret_cast<uint8_t *>(input),
                       sizeof(input));
    }}
    res_check_publish_inputs(res_check_sync, tid);
#endif
    BENCHSTART;
    supernpu::multi_thread::argmaxv2<{ctype}, {idtype}, {axis}{dim_args}>(
        input, output);
    BENCHEND;
#ifdef RES_CHECK
    res_check_wait_for_all(res_check_sync, tid);
    if (tid == 0) {{
        writeBinaryFile(CHK_DIR "/output.bin",
                        reinterpret_cast<uint8_t *>(output), sizeof(output));
    }}
#endif
    return 0;
}}
"""


def gen_sources() -> None:
    src_dir = HERE / "src"
    src_dir.mkdir(exist_ok=True)
    for i, (cid, dims, dtype, idtype) in enumerate(CASES):
        rank = len(dims)
        total = int(np.prod(dims))
        desc = f"{dtype}/{idtype} ax{AXIS} {list(dims)}"
        size_asserts = (f'static_assert(sizeof({CTYPE[dtype]}) == 2, "16-bit dtype");'
                        if dtype in ("fp16", "bf16") else "")
        (src_dir / f"{cid}.cpp").write_text(CPP_TEMPLATE.format(
            cid=cid, desc=desc, rank=rank,
            dim_defs="\n".join(f"constexpr int kD{j} = {d};" for j, d in enumerate(dims)),
            ctype=CTYPE[dtype], idtype="int64_t" if idtype == "i64" else "int32_t",
            total=total, out_total=dims[0], size_asserts=size_asserts,
            axis=AXIS, dim_args="".join(f", kD{j}" for j in range(rank))),
            encoding="utf-8")
    print(f"[GEN] {len(CASES)} cases -> {src_dir}", flush=True)


def build_one(cid: str, suffix: str, res_check: bool, log_dir: Path,
               disable_rsplit: bool = False) -> tuple[str, str]:
    log = log_dir / f"{cid}.build.log"
    cmd = ["make", f"TESTCASE={cid}", f"COMPILER_DIR={COMPILER_DIR}"]
    if res_check:
        cmd.append("res_check=on")
    else:
        cmd.append(f"SUFFIX={suffix}")
    if disable_rsplit:
        cmd.append("EXTRA_DEFINES=-DARGMAXV2_DISABLE_RSPLIT")
    try:
        proc = subprocess.run(cmd, cwd=HERE, stdout=subprocess.PIPE,
                              stderr=subprocess.STDOUT, text=True, timeout=3600)
        log.write_text(proc.stdout, encoding="utf-8")
        elf = OUTPUT / "elf" / f"kernel_argmaxv2_{cid}_PE4{suffix}.elf"
        if proc.returncode != 0 or not elf.is_file():
            return "BUILD_FAIL", f"rc={proc.returncode}; log={log}"
        return "PASS", "built"
    except subprocess.TimeoutExpired:
        return "BUILD_FAIL", "build timeout"


def prepare_data(cid: str, dims, dtype: str, idtype: str) -> np.ndarray:
    case_dir = COMPARE / f"kernel_argmaxv2_{cid}_PE4"
    case_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(abs(hash(cid)) % (2**32))
    out_np = np.int64 if idtype == "i64" else np.int32
    if dtype == "i32":
        x = rng.integers(-1_000_000, 1_000_000, dims).astype(np.int32)
        np.ascontiguousarray(x).tofile(case_dir / "input.bin")
        golden = np.argmax(x, axis=AXIS)
    else:
        f32 = rng.uniform(-1.0, 1.0, dims).astype(np.float32)
        if dtype == "fp32":
            np.ascontiguousarray(f32).tofile(case_dir / "input.bin")
            golden = np.argmax(f32, axis=AXIS)
        elif dtype == "fp16":
            f16 = f32.astype(np.float16)
            np.ascontiguousarray(f16).tofile(case_dir / "input.bin")
            golden = np.argmax(f16, axis=AXIS)
        else:  # bf16: top 16 bits; golden on exact fp32 reconstruction
            bits = (f32.view(np.uint32) >> 16).astype(np.uint16)
            bits.tofile(case_dir / "input.bin")
            recon = (bits.astype(np.uint32) << 16).view(np.float32).reshape(dims)
            golden = np.argmax(recon, axis=AXIS)
    golden = np.asarray(golden).reshape(-1).astype(out_np)
    np.full(golden.size, -1, dtype=out_np).tofile(case_dir / "output.bin")
    return golden


def run_acc_one(cid, dims, dtype, idtype) -> dict:
    elf = OUTPUT / "elf" / f"kernel_argmaxv2_{cid}_PE4.elf"
    case_dir = COMPARE / f"kernel_argmaxv2_{cid}_PE4"
    golden = prepare_data(cid, dims, dtype, idtype)
    row = dict(cid=cid, status="TEST_INFRA_FAIL", detail="", mismatches="",
               elapsed_s="", log=str(case_dir / "gfrun.log"))
    if not elf.is_file():
        row["detail"] = "missing ELF"
        return row
    t0 = time.time()
    try:
        proc = subprocess.run([str(GFRUN), "-s", "softcore.multiThreadNum=4",
                               "-f", str(elf)],
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                              text=True, timeout=GFRUN_TIMEOUT)
    except subprocess.TimeoutExpired:
        row["status"], row["detail"] = "TIMEOUT", f"gfrun >{GFRUN_TIMEOUT}s"
        return row
    (case_dir / "gfrun.log").write_text(proc.stdout, encoding="utf-8")
    row["elapsed_s"] = round(time.time() - t0, 1)
    if proc.returncode != 0:
        row["status"], row["detail"] = "MODEL_FAIL", f"gfrun rc={proc.returncode}"
        return row
    if ("Reach the End of Benchmark" not in proc.stdout or "R2 = 0" not in proc.stdout
            or "data write to file done" not in proc.stdout):
        row["status"], row["detail"] = "MODEL_FAIL", "missing end/file markers"
        return row
    out_np = np.int64 if idtype == "i64" else np.int32
    actual = np.fromfile(case_dir / "output.bin", dtype=out_np)
    if actual.size != golden.size:
        row["status"] = "ACCURACY_FAIL"
        row["detail"] = f"size actual={actual.size} golden={golden.size}"
        return row
    bad = np.nonzero(actual != golden)[0]
    row["mismatches"] = int(bad.size)
    if bad.size:
        row["status"] = "ACCURACY_FAIL"
        row["detail"] = "; ".join(f"[{i}] got={actual[i]} want={golden[i]}"
                                  for i in bad[:8])
    else:
        row["status"], row["detail"] = "PASS", "exact match"
    return row


def run_perf_one(cid, suffix="_t", vdir=None) -> dict:
    elf = OUTPUT / "elf" / f"kernel_argmaxv2_{cid}_PE4{suffix}.elf"
    out_dir = (vdir or VALIDATION) / cid
    out_dir.mkdir(parents=True, exist_ok=True)
    row = dict(cid=cid, status="TEST_INFRA_FAIL", total_cycles="NA", waw="NA",
               exit_code="NA", wall_s="", pe_active="", vec_cycles="",
               tlsu_cycles="", log="", cycles_source="standard")
    if not elf.is_file():
        row["log"] = "missing ELF"
        return row
    cmd = ["bash", str(SKILL_SCRIPT), "--model-dir", str(MODEL_DIR),
           "--elf", str(elf), "--case", cid, "--out-dir", str(out_dir),
           "--mode", "real", "--soc", "random", "--soc-seed", "2",
           "--timeout", str(GFSIM_TIMEOUT)]
    t0 = time.time()
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True)
    row["wall_s"] = round(time.time() - t0, 1)
    summary = out_dir / "summary.tsv"
    if summary.is_file():
        import csv
        rows = list(csv.DictReader(open(summary), delimiter="\t"))
        if rows:
            r = rows[-1]
            row.update(status=r["status"], total_cycles=r["total_cycles"],
                       waw=r["scb_waw_violation"], exit_code=r["exit_code"],
                       log=r["log"])
    if row["status"] == "DEADLOCK":
        # established single-variable diagnostic: raise watchdog threshold only
        diag_log = out_dir / f"{cid}-deadlock1m-diagnostic.log"
        dcmd = ["timeout", str(GFSIM_TIMEOUT), str(MODEL_DIR / "bin/gfsim"),
                "-f", str(elf), "--conf", "fourpe", "--pto-v02", "true",
                "-s", "tlsu.fake_l2_enable=false", "-s", "core.soc_random=true",
                "-s", "core.soc_lat_random_seed=2",
                "-s", f"core.deadlock_cycles={DIAG_DEADLOCK_CYCLES}"]
        t1 = time.time()
        d = subprocess.run(dcmd, cwd=MODEL_DIR, stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT, text=True)
        diag_log.write_text(d.stdout, encoding="utf-8")
        cyc = None
        for line in d.stdout.splitlines():
            if line.startswith("Total Cycles"):
                cyc = line.split()[-1]
                break
        if d.returncode == 0 and cyc:
            row["total_cycles"] = cyc
            row["cycles_source"] = "deadlock_cycles=1e6 diagnostic"
        row["wall_s"] = round(row["wall_s"] + time.time() - t1, 1)
    # per-PE vector activity + engine cycles from the effective log
    logf = None
    if row["status"] == "PASS":
        logf = Path(row["log"]) if row["log"] else None
    elif (out_dir / f"{cid}-deadlock1m-diagnostic.log").is_file():
        logf = out_dir / f"{cid}-deadlock1m-diagnostic.log"
    if logf and logf.is_file():
        import re
        text = logf.read_text(errors="replace")
        active = []
        for pe in range(4):
            m = re.search(rf"Vector PMU Stats PE{pe}.*?TileopNum\.+:\s*(\d+)",
                          text, re.S)
            if m and int(m.group(1)) > 0:
                active.append(pe)
        row["pe_active"] = ",".join(map(str, active))
        m = re.search(r"Vector Tileop Total Cycles\.+:\s*(\d+)", text)
        row["vec_cycles"] = m.group(1) if m else ""
        m = re.search(r"TLSU Tileop Total Cycles\.+:\s*(\d+)", text)
        row["tlsu_cycles"] = m.group(1) if m else ""
    return row


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", choices=["gen", "acc", "perf"], default="gen")
    ap.add_argument("--build-jobs", type=int, default=8)
    ap.add_argument("--run-jobs", type=int, default=4)
    ap.add_argument("--disable-rsplit", action="store_true",
                    help="A/B baseline: -DARGMAXV2_DISABLE_RSPLIT, SUFFIX=_tb")
    args = ap.parse_args()

    if args.phase == "gen":
        gen_sources()
        return 0
    suffix = "_tb" if args.disable_rsplit else "_t"

    VALIDATION.mkdir(parents=True, exist_ok=True)
    (VALIDATION / "build").mkdir(exist_ok=True)

    if args.phase == "acc":
        with ThreadPoolExecutor(max_workers=args.build_jobs) as pool:
            builds = dict(zip([c[0] for c in CASES], pool.map(
                lambda c: build_one(c[0], "", True, VALIDATION / "build"),
                CASES)))
        failed = [c for c, (s, _) in builds.items() if s != "PASS"]
        print(f"[BUILD] {len(CASES) - len(failed)}/{len(CASES)} accuracy ELFs built"
              + (f"; failed: {failed}" if failed else ""), flush=True)
        runnable = [c for c in CASES if builds[c[0]][0] == "PASS"]
        rows = []
        with ThreadPoolExecutor(max_workers=args.run_jobs) as pool:
            for r in pool.map(lambda c: run_acc_one(*c), runnable):
                rows.append(r)
                flag = "" if r["status"] == "PASS" else f" <<<< {r['status']}"
                print(f"[ACC] {r['cid']} {r['status']} mismatches={r['mismatches']}"
                      f" {r['elapsed_s']}s{flag}", flush=True)
        tsv = VALIDATION / "accuracy.tsv"
        with tsv.open("w") as f:
            f.write("cid\tdims\tdtype\tidtype\telems\tstatus\tdetail\t"
                    "mismatches\telapsed_s\tlog\n")
            for (cid, dims, dtype, idtype), r in zip(CASES, rows + [None] * (len(CASES) - len(rows))):
                if r is None:
                    continue
                f.write("\t".join(str(x) for x in [
                    cid, ",".join(map(str, dims)), dtype, idtype,
                    int(np.prod(dims)), r["status"], r["detail"],
                    r["mismatches"], r["elapsed_s"], r["log"]]) + "\n")
        ok = sum(1 for r in rows if r["status"] == "PASS")
        print(f"[ACC SUMMARY] {ok}/{len(rows)} PASS -> {tsv}", flush=True)
        return 0 if ok == len(rows) else 1

    if args.phase == "perf":
        with ThreadPoolExecutor(max_workers=args.build_jobs) as pool:
            builds = dict(zip([c[0] for c in CASES], pool.map(
                lambda c: build_one(c[0], suffix, False, VALIDATION / "build",
                    disable_rsplit=args.disable_rsplit),
                CASES)))
        failed = [c for c, (s, _) in builds.items() if s != "PASS"]
        print(f"[BUILD] {len(CASES) - len(failed)}/{len(CASES)} timing ELFs built"
              + (f"; failed: {failed}" if failed else ""), flush=True)
        runnable = [c[0] for c in CASES if builds[c[0]][0] == "PASS"]
        rows = []
        t0 = time.time()
        with ThreadPoolExecutor(max_workers=args.run_jobs) as pool:
            for i, r in enumerate(pool.map(lambda c: run_perf_one(c, suffix, VALIDATION / ("baseline" if args.disable_rsplit else "timing")), runnable), 1):
                rows.append(r)
                flag = "" if r["status"] == "PASS" else f" <<<< {r['status']}"
                print(f"[RUN {i}/{len(runnable)}] {r['cid']} cycles={r['total_cycles']}"
                      f" ({r['cycles_source']}) PE[{r['pe_active']}] {r['wall_s']}s{flag}",
                      flush=True)
        tsv = VALIDATION / "perf.tsv"
        with tsv.open("w") as f:
            f.write("cid\tdims\tdtype\tidtype\telems\tstatus\ttotal_cycles\t"
                    "cycles_source\tvec_cycles\ttlsu_cycles\twaw\tpe_active\t"
                    "exit_code\twall_s\tlog\n")
            meta = {c[0]: c for c in CASES}
            for r in rows:
                cid, dims, dtype, idtype = meta[r["cid"]]
                f.write("\t".join(str(x) for x in [
                    cid, ",".join(map(str, dims)), dtype, idtype,
                    int(np.prod(dims)), r["status"], r["total_cycles"],
                    r["cycles_source"], r["vec_cycles"], r["tlsu_cycles"],
                    r["waw"], r["pe_active"], r["exit_code"], r["wall_s"],
                    r["log"]]) + "\n")
        print(f"[PERF SUMMARY] ({time.time()-t0:.0f}s) -> {tsv}", flush=True)
        return 0

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
