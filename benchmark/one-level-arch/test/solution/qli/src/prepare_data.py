#!/usr/bin/env python3
"""Validate QLI data provenance and emit a symbol-based assembly object."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--out", type=Path, required=True)
parser.add_argument("--sq", type=int, required=True)
parser.add_argument("--skv", type=int, required=True)
parser.add_argument("--topk", type=int, required=True)
parser.add_argument("--heads", type=int, default=64)
parser.add_argument("--batch", type=int, default=1)
parser.add_argument("--tile-k", type=int, default=32)
parser.add_argument("--npe", type=int, default=1)
parser.add_argument("--dtype", choices=("fp8", "int8"), default="fp8")
args = parser.parse_args()

if args.batch != 1:
    raise SystemExit("QLI data integration currently supports exactly batch=1")
if args.sq <= 0 or args.skv <= 0 or args.topk <= 0 or args.heads <= 0:
    raise SystemExit("Sq, Skv, topk, and heads must be positive")
if args.topk > args.skv:
    raise SystemExit("topk must not exceed Skv")
if args.tile_k <= 0 or args.skv % args.tile_k:
    raise SystemExit("Skv must be divisible by the configured key tile width")
if args.npe <= 0 or args.sq % args.npe:
    raise SystemExit("NPE must be positive and divide Sq")

out = args.out.resolve()
out.mkdir(parents=True, exist_ok=True)
sizes = {
    "srcq": args.sq * args.heads * 128,
    "srck": args.skv * 128,
    "srcw": args.sq * args.heads * 4,
    "srcsq": args.sq * args.heads * 4,
    "srcsk": args.skv * 4,
    "reference_scores": args.sq * args.skv * 4,
    "reference_indices": args.sq * args.topk * 4,
}
config = {
    "batch": 1,
    "dtype": args.dtype,
    "sq": args.sq,
    "skv": args.skv,
    "topk": args.topk,
    "heads": args.heads,
    "d": 128,
}
manifest_path = out / "manifest.json"
generator_path = Path(__file__).with_name("gen_qli_golden.py")


def digest(path):
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def load_manifest():
    try:
        return json.loads(manifest_path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def expected_provenance():
    if args.dtype == "fp8":
        return {"kind": "generated", "generator_sha256": digest(generator_path)}
    return None


def validate(manifest):
    if not isinstance(manifest, dict) or manifest.get("schema_version") != 1:
        return False
    if manifest.get("config") != config:
        return False
    provenance = manifest.get("provenance")
    if args.dtype == "fp8":
        if provenance != expected_provenance():
            return False
    elif (not isinstance(provenance, dict) or
          provenance.get("kind") != "external" or
          not isinstance(provenance.get("source"), str) or
          not provenance["source"]):
        return False
    files = manifest.get("files")
    if not isinstance(files, dict) or set(files) != set(sizes):
        return False
    for name, size in sizes.items():
        path = out / f"{name}.bin"
        record = files.get(name)
        if (not path.is_file() or not isinstance(record, dict) or
                record.get("size") != size or path.stat().st_size != size or
                record.get("sha256") != digest(path)):
            return False
    return True


if not validate(load_manifest()):
    if args.dtype == "int8":
        raise SystemExit(
            "INT8 requires externally generated inputs/goldens and a valid "
            "matching manifest.json; no INT8 generator is provided")
    with tempfile.TemporaryDirectory(prefix="qli-golden-",
                                     dir=out.parent) as temp:
        generated = Path(temp)
        subprocess.run(
            [sys.executable,
             str(generator_path),
             "--mode", "gen", "--outdir", str(generated),
             "--sq", str(args.sq), "--skv", str(args.skv),
             "--topk", str(args.topk), "--g", str(args.heads),
             "--d", "128"],
            check=True)
        for name, size in sizes.items():
            path = generated / f"{name}.bin"
            if not path.is_file() or path.stat().st_size != size:
                raise SystemExit(f"{path}: expected {size} generated bytes")
        for name in sizes:
            os.replace(generated / f"{name}.bin", out / f"{name}.bin")
    files = {
        name: {"size": size, "sha256": digest(out / f"{name}.bin")}
        for name, size in sizes.items()
    }
    manifest = {"schema_version": 1, "config": config,
                "provenance": expected_provenance(), "files": files}
    temporary_manifest = manifest_path.with_suffix(".json.tmp")
    temporary_manifest.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    os.replace(temporary_manifest, manifest_path)

if not validate(load_manifest()):
    raise SystemExit("QLI data manifest validation failed after preparation")

assembly = [".section .data", ".balign 64"]
for name in ("srcq", "srck", "srcw", "srcsq", "srcsk"):
    size = sizes[name]
    path = out / f"{name}.bin"
    if '"' in str(path) or "\n" in str(path):
        raise SystemExit("data path cannot contain quotes or newlines")
    symbol = f"_binary_{name}_data"
    assembly += [
        ".balign 64",
        f".global {symbol}_start",
        f".type {symbol}_start,@object",
        f"{symbol}_start:",
        f'.incbin "{path}"',
        f".size {symbol}_start,.-{symbol}_start",
        f".global {symbol}_end",
        f"{symbol}_end:",
        f".global {symbol}_size",
        f".equ {symbol}_size,.-{symbol}_start",
    ]
(out / "qli_data.s").write_text("\n".join(assembly) + "\n")
(out / "prepared.stamp").write_text(digest(manifest_path) + "\n")
